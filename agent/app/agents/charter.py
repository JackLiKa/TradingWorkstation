def _extract_key_conclusions(history_summary: str, n: int = 2) -> str:
    """從歷史摘要中提取最近 n 輪的關鍵結論（最佳策略評分、主要改進方向）。

    Args:
        history_summary: 歷史迭代摘要文本（每行一輪，含評分/收益/回撤/夏普等）
        n: 提取最近幾輪

    Returns:
        str: 關鍵結論文本，無有效歷史時返回空字符串
    """
    if not history_summary or history_summary.strip() in ("無", "無（首輪）", ""):
        return ""

    lines = [ln.strip() for ln in history_summary.strip().splitlines() if ln.strip()]
    if not lines:
        return ""

    # 取最後 n 行
    recent = lines[-n:]
    conclusions = ["## 最近關鍵結論（從歷史記錄提取，僅供參考）"]
    for ln in recent:
        conclusions.append(f"- {ln}")
    conclusions.append("注意：以上歷史結論僅供參考，可能失效，請基於當前數據獨立判斷。")
    return "\n".join(conclusions)


def get_recall_with_memory(iteration: int, history_summary: str = "") -> str:
    """根據迭代輪次 + 歷史摘要返回帶記憶的回憶文本。

    iteration 2-5：返回擴展版 RECALL_SUMMARY + 最近 2 輪關鍵結論
    iteration > 5：返回精簡版 RECALL_SUMMARY_COMPACT + 最近 3 輪關鍵結論
    iteration <= 1：返回完整憲章（不在此處處理，由 get_charter 負責）

    Args:
        iteration: 當前迭代輪次（從 1 開始）
        history_summary: 歷史迭代摘要文本（每行一輪）

    Returns:
        str: 帶記憶的回憶文本
    """
    if iteration <= 1:
        return FULL_CHARTER

    if iteration <= 5:
        base = RECALL_SUMMARY
        conclusions = _extract_key_conclusions(history_summary, n=2)
    else:
        base = RECALL_SUMMARY_COMPACT
        conclusions = _extract_key_conclusions(history_summary, n=3)

    if conclusions:
        return f"{base}\n\n{conclusions}"
    return base


